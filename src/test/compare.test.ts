async function roundTrip(cfg: ConnectionConfig, src: string, tgt: string, srcDb: string, tgtDb: string, setup: string[]) {
  const { driver: d, dispose } = createDriver(cfg);
  try {
    for (const s of setup) await run(d, cfg.kind === 'postgres' ? srcDb : '', s);
    const a = await d.snapshot(srcDb, src);
    const b = await d.snapshot(tgtDb, tgt);
    const diff = diffSchemas(a, b, { targetSchema: tgt });
    const byId = new Map(diff.items.map((i) => [i.id, i]));
    await t('différences détectées', () => {
      assert.equal(byId.get('table:lignes')?.status, 'added');
      assert.equal(byId.get('table:archive')?.status, 'removed');
      assert.equal(byId.get('table:produits')?.status, 'changed');
      assert.equal(byId.get('table:commandes'), undefined, 'commandes identique');
      const p = byId.get('table:produits')!;
      assert.ok(p.details.some((x) => x.includes('ancien_prix')), 'colonne supprimée détectée');
      assert.ok(p.details.some((x) => x.includes('sku')), 'type sku');
      assert.ok(p.destructive, 'suppression de colonne = destructif');
      assert.equal(byId.get('view:v_catalogue')?.status, 'changed');
      assert.equal(byId.get('view:v_obsolete')?.status, 'removed');
      assert.ok([...byId.values()].some((i) => i.type === 'function' && i.status === 'changed'));
      assert.ok([...byId.values()].some((i) => i.type === 'trigger' && i.status === 'added'));
    });
    const visible = diff.items.filter((i) => !i.auto);
    await t('vues identiques à recréer : masquées mais ajoutées au script', () => {
      if (cfg.kind !== 'postgres') return;
      const onlyProduits = buildScript(cfg.kind, visible.filter((i) => i.id === 'table:produits'), undefined, diff.items);
      assert.ok(!visible.some((i) => i.name === 'v_skus'), 'v_skus masquée');
      // dépendance transitive : v_nb_skus dépend de v_skus ; suppression avant, création après
      const iNb = onlyProduits.indexOf('DROP VIEW IF EXISTS "cmp_tgt"."v_nb_skus"');
      const iSk = onlyProduits.indexOf('DROP VIEW IF EXISTS "cmp_tgt"."v_skus"');
      assert.ok(iNb >= 0 && iSk > iNb, 'ordre de suppression');
      assert.ok(onlyProduits.indexOf('CREATE VIEW "cmp_tgt"."v_skus"') < onlyProduits.indexOf('CREATE VIEW "cmp_tgt"."v_nb_skus"'), 'ordre de création');
      const none = buildScript(cfg.kind, visible.filter((i) => i.id === 'table:lignes'), undefined, diff.items);
      assert.doesNotMatch(none, /v_skus/);
    });
    const script = buildScript(cfg.kind, visible, 'test', diff.items);
    await t('script appliqué sur la cible sans erreur', async () => {
      await run(d, tgtDb, cfg.kind === 'postgres' ? `BEGIN;\n${script}\nCOMMIT;` : script);
    });
    await t('nouvelle comparaison : schémas identiques', async () => {
      const again = diffSchemas(await d.snapshot(srcDb, src), await d.snapshot(tgtDb, tgt), { targetSchema: tgt });
      assert.deepEqual(
        again.items.map((i) => `${i.id} ${i.status}: ${i.details.join(' | ')}`),
        [],
      );
    });
    await t('données conservées et trigger actif', async () => {
      const r = await d.execute('cmp2', tgtDb, [
        cfg.kind === 'postgres' ? `insert into ${tgt}.produits(sku, libelle) values ('b2', 'B')` : `insert into produits(sku, libelle) values ('b2', 'B')`,
        cfg.kind === 'postgres' ? `select sku from ${tgt}.produits order by sku` : `select sku from produits order by sku`,
      ], 10);
      assert.deepEqual(r[1].rows.map((x) => String(x[0])).sort(), ['B2', 'a1']);
    });
    if (cfg.kind === 'postgres') await run(d, srcDb, 'drop schema cmp_src cascade; drop schema cmp_tgt cascade');
    else await run(d, '', 'drop database cmp_src; drop database cmp_tgt');
  } finally {
    await d.close();
    dispose();
  }
}

async function main() {
  console.log('Analyse de SHOW CREATE TABLE');
  await t('colonnes, clés, FK, commentaire', () => {
    const tb = parseMysqlCreate(
      'x',
      'CREATE TABLE `x` (\n  `id` int(11) NOT NULL AUTO_INCREMENT,\n  `a` varchar(10) DEFAULT \'o,k\',\n  PRIMARY KEY (`id`),\n  UNIQUE KEY `uk_a` (`a`),\n  CONSTRAINT `fk` FOREIGN KEY (`a`) REFERENCES `autre`.`y` (`b`) ON DELETE CASCADE\n) ENGINE=InnoDB AUTO_INCREMENT=42 DEFAULT CHARSET=utf8mb4 COMMENT=\'C\'\'est\'',
    );
    assert.deepEqual(tb.columns.map((c) => c.name), ['id', 'a']);
    assert.equal(tb.columns[1].def, "varchar(10) DEFAULT 'o,k'");
    assert.deepEqual(tb.pk, { name: 'PRIMARY', columns: ['id'] });
    assert.equal(tb.indexes[0].unique, true);
    assert.deepEqual([tb.fks[0].refSchema, tb.fks[0].refTable, tb.fks[0].onDelete], ['autre', 'y', 'CASCADE']);
    assert.equal(tb.comment, "C'est");
    assert.ok(!/AUTO_INCREMENT=42/.test(tb.createSql!));
  });

  console.log('\nPostgreSQL : cmp_src → cmp_tgt');
  await roundTrip(base, 'cmp_src', 'cmp_tgt', 'boutique', 'boutique', [PG_SOURCE, PG_TARGET]);

  console.log('\nMariaDB : cmp_src → cmp_tgt');
  await roundTrip(
    { ...base, id: 'my', kind: 'mysql', port: Number(env.KSDB_MY_PORT ?? 3306), user: env.KSDB_MY_USER ?? 'ks', password: env.KSDB_MY_PASS ?? 'secret', database: '' },
    'cmp_src',
    'cmp_tgt',
    'cmp_src',
    'cmp_tgt',
    [MY_SOURCE, MY_TARGET],
  );

  console.log(failed ? `\n${failed} test(s) en échec` : '\nTous les tests de comparaison passent');
  process.exit(failed ? 1 : 0);
}

main();
