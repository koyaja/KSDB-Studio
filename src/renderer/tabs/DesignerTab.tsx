import { ArrowDown, ArrowUp, Code2, Play, Plus, RotateCcw, Trash2, Undo2 } from 'lucide-react';
import { useEffect, useMemo, useState } from 'react';
import type { DbKind, TableStructure } from '../../shared/types';
import { quoteIdent } from '../actions';
import { api } from '../api';
import { bumpTree, confirmDialog, connectionById, Tab, toast, uid, updateTab, useApp } from '../state';
import { invalidateCompletion } from './QueryTab';

type DTab = Extract<Tab, { kind: 'designer' }>;

interface Col {
  key: string;
  orig: TableStructure['columns'][number] | null;
  name: string;
  type: string;
  nullable: boolean;
  def: string;
  comment: string;
  pk: boolean;
  auto: boolean;
  removed: boolean;
}

interface NewIndex {
  key: string;
  name: string;
  columns: string;
  unique: boolean;
}

interface NewFk {
  key: string;
  name: string;
  columns: string;
  refTable: string;
  refColumns: string;
  onDelete: string;
  onUpdate: string;
}

const PG_TYPES = ['integer', 'bigint', 'smallint', 'numeric(12,2)', 'real', 'double precision', 'text', 'varchar(255)', 'char(1)', 'boolean', 'date', 'timestamp', 'timestamptz', 'time', 'interval', 'uuid', 'jsonb', 'json', 'bytea', 'inet', 'text[]', 'integer[]'];
const MY_TYPES = ['int', 'bigint', 'smallint', 'tinyint(1)', 'decimal(12,2)', 'double', 'float', 'varchar(255)', 'char(36)', 'text', 'mediumtext', 'longtext', 'date', 'datetime', 'timestamp', 'time', 'year', 'json', 'blob', 'enum(\'a\',\'b\')'];
const FK_ACTIONS = ['NO ACTION', 'RESTRICT', 'CASCADE', 'SET NULL', 'SET DEFAULT'];

const fromStructure = (st: TableStructure): Col[] =>
  st.columns.map((c) => ({
    key: uid(),
    orig: c,
    name: c.name,
    type: c.type,
    nullable: c.nullable,
    def: c.autoIncrement && /^nextval\(/i.test(c.default ?? '') ? c.default ?? '' : c.default ?? '',
    comment: c.comment ?? '',
    pk: c.isPrimaryKey,
    auto: c.autoIncrement,
    removed: false,
  }));

const blankCol = (kind: DbKind, first: boolean): Col => ({
  key: uid(),
  orig: null,
  name: first ? 'id' : '',
  type: first ? (kind === 'postgres' ? 'bigint' : 'bigint') : kind === 'postgres' ? 'text' : 'varchar(255)',
  nullable: !first,
  def: '',
  comment: '',
  pk: first,
  auto: first,
  removed: false,
});

function identList(kind: DbKind, s: string) {
  return s
    .split(',')
    .map((x) => x.trim())
    .filter(Boolean)
    .map((x) => (/^[A-Za-z_][A-Za-z0-9_$]*$/.test(x) ? quoteIdent(kind, x) : x))
    .join(', ');
}

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function generateSql(
  kind: DbKind,
  qTable: string,
  isNew: boolean,
  cols: Col[],
  orig: TableStructure | null,
  tableComment: string,
  indexes: NewIndex[],
  dropIndexes: string[],
  fks: NewFk[],
  dropFks: string[],
  schema: string,
): string[] {
  const q = (n: string) => quoteIdent(kind, n);
  const live = cols.filter((c) => !c.removed && c.name.trim());
  const pkCols = live.filter((c) => c.pk).map((c) => c.name);
  const out: string[] = [];

  const colDefMy = (c: Col) =>
    `${q(c.name)} ${c.type}${c.nullable ? ' NULL' : ' NOT NULL'}${c.def.trim() ? ` DEFAULT ${c.def.trim()}` : ''}${c.auto ? ' AUTO_INCREMENT' : ''}${c.comment ? ` COMMENT ${lit(c.comment)}` : ''}`;
  const colDefPg = (c: Col) =>
    `${q(c.name)} ${c.type}${c.auto && !/serial/i.test(c.type) && !/^nextval/i.test(c.def) ? ' GENERATED BY DEFAULT AS IDENTITY' : c.def.trim() ? ` DEFAULT ${c.def.trim()}` : ''}${c.nullable ? '' : ' NOT NULL'}`;

  if (isNew) {
    const lines = live.map((c) => '  ' + (kind === 'postgres' ? colDefPg(c) : colDefMy(c)));
    if (pkCols.length) lines.push(`  PRIMARY KEY (${pkCols.map(q).join(', ')})`);
    for (const f of fks)
      if (f.columns && f.refTable)
        lines.push(
          `  ${f.name ? `CONSTRAINT ${q(f.name)} ` : ''}FOREIGN KEY (${identList(kind, f.columns)}) REFERENCES ${f.refTable.includes('.') ? f.refTable : q(f.refTable)} (${identList(kind, f.refColumns)}) ON DELETE ${f.onDelete} ON UPDATE ${f.onUpdate}`,
        );
    let sql = `CREATE TABLE ${qTable} (\n${lines.join(',\n')}\n)`;
    if (kind === 'mysql') sql += ` ENGINE=InnoDB DEFAULT CHARSET=utf8mb4${tableComment ? ` COMMENT=${lit(tableComment)}` : ''}`;
    out.push(sql);
    if (kind === 'postgres') {
      if (tableComment) out.push(`COMMENT ON TABLE ${qTable} IS ${lit(tableComment)}`);
      for (const c of live) if (c.comment) out.push(`COMMENT ON COLUMN ${qTable}.${q(c.name)} IS ${lit(c.comment)}`);
    }
  } else if (orig) {
    const origPk = orig.primaryKey;
    const pkChanged = origPk.join('|') !== pkCols.join('|') || cols.some((c) => c.removed && c.pk);
    if (kind === 'postgres') {
      if (pkChanged && orig.primaryKeyName) out.push(`ALTER TABLE ${qTable} DROP CONSTRAINT ${q(orig.primaryKeyName)}`);
      for (const c of cols) if (c.removed && c.orig) out.push(`ALTER TABLE ${qTable} DROP COLUMN ${q(c.orig.name)}`);
      for (const c of live) {
        if (!c.orig) continue;
        const o = c.orig;
        if (c.name !== o.name) out.push(`ALTER TABLE ${qTable} RENAME COLUMN ${q(o.name)} TO ${q(c.name)}`);
        const n = q(c.name);
        if (c.type !== o.type) out.push(`ALTER TABLE ${qTable} ALTER COLUMN ${n} TYPE ${c.type} USING ${n}::${c.type}`);
        if (c.nullable !== o.nullable) out.push(`ALTER TABLE ${qTable} ALTER COLUMN ${n} ${c.nullable ? 'DROP' : 'SET'} NOT NULL`);
        const od = o.default ?? '';
        if (c.def.trim() !== od && !(c.auto && /^nextval/i.test(od)))
          out.push(`ALTER TABLE ${qTable} ALTER COLUMN ${n} ${c.def.trim() ? `SET DEFAULT ${c.def.trim()}` : 'DROP DEFAULT'}`);
        if (c.auto !== o.autoIncrement && !/^nextval/i.test(od))
          out.push(c.auto ? `ALTER TABLE ${qTable} ALTER COLUMN ${n} ADD GENERATED BY DEFAULT AS IDENTITY` : `ALTER TABLE ${qTable} ALTER COLUMN ${n} DROP IDENTITY IF EXISTS`);
        if (c.comment !== (o.comment ?? '')) out.push(`COMMENT ON COLUMN ${qTable}.${n} IS ${c.comment ? lit(c.comment) : 'NULL'}`);
      }
      for (const c of live) {
        if (c.orig) continue;
        out.push(`ALTER TABLE ${qTable} ADD COLUMN ${colDefPg(c)}`);
        if (c.comment) out.push(`COMMENT ON COLUMN ${qTable}.${q(c.name)} IS ${lit(c.comment)}`);
      }
      if (pkChanged && pkCols.length) out.push(`ALTER TABLE ${qTable} ADD PRIMARY KEY (${pkCols.map(q).join(', ')})`);
      if (tableComment !== (orig.comment ?? '')) out.push(`COMMENT ON TABLE ${qTable} IS ${tableComment ? lit(tableComment) : 'NULL'}`);
    } else {
      const clauses: string[] = [];
      if (pkChanged && origPk.length) clauses.push('DROP PRIMARY KEY');
      for (const c of cols) if (c.removed && c.orig) clauses.push(`DROP COLUMN ${q(c.orig.name)}`);
      let prev: string | null = null;
      for (const c of live) {
        if (c.orig) {
          const o = c.orig;
          const changed =
            c.name !== o.name || c.type !== o.type || c.nullable !== o.nullable || c.def.trim() !== (o.default ?? '') || c.auto !== o.autoIncrement || c.comment !== (o.comment ?? '');
          if (changed) clauses.push(`CHANGE COLUMN ${q(o.name)} ${colDefMy(c)}`);
        } else clauses.push(`ADD COLUMN ${colDefMy(c)} ${prev ? `AFTER ${q(prev)}` : 'FIRST'}`);
        prev = c.name;
      }
      if (pkChanged && pkCols.length) clauses.push(`ADD PRIMARY KEY (${pkCols.map(q).join(', ')})`);
      if (tableComment !== (orig.comment ?? '')) clauses.push(`COMMENT = ${lit(tableComment)}`);
      if (clauses.length) out.push(`ALTER TABLE ${qTable}\n  ${clauses.join(',\n  ')}`);
    }
    for (const n of dropFks) out.push(kind === 'postgres' ? `ALTER TABLE ${qTable} DROP CONSTRAINT ${q(n)}` : `ALTER TABLE ${qTable} DROP FOREIGN KEY ${q(n)}`);
    for (const f of fks)
      if (f.columns && f.refTable)
        out.push(
          `ALTER TABLE ${qTable} ADD ${f.name ? `CONSTRAINT ${q(f.name)} ` : ''}FOREIGN KEY (${identList(kind, f.columns)}) REFERENCES ${f.refTable.includes('.') ? f.refTable : q(f.refTable)} (${identList(kind, f.refColumns)}) ON DELETE ${f.onDelete} ON UPDATE ${f.onUpdate}`,
        );
  }
  for (const n of dropIndexes) out.push(kind === 'postgres' ? `DROP INDEX ${q(schema)}.${q(n)}` : `DROP INDEX ${q(n)} ON ${qTable}`);
  for (const i of indexes)
    if (i.columns.trim()) out.push(`CREATE ${i.unique ? 'UNIQUE ' : ''}INDEX ${i.name ? q(i.name) + ' ' : ''}ON ${qTable} (${identList(kind, i.columns)})`);
  return out;
}

export function DesignerTab({ tab, active }: { tab: DTab; active: boolean }) {
  const conn = useApp((s) => s.connections.find((c) => c.id === tab.connectionId));
  const kind: DbKind = conn?.kind ?? 'postgres';
  const isNew = tab.table === null;
  const [orig, setOrig] = useState<TableStructure | null>(null);
  const [name, setName] = useState(tab.table ?? '');
  const [cols, setCols] = useState<Col[]>(isNew ? [blankCol(kind, true), blankCol(kind, false)] : []);
  const [comment, setComment] = useState('');
  const [indexes, setIndexes] = useState<NewIndex[]>([]);
  const [dropIdx, setDropIdx] = useState<string[]>([]);
  const [fks, setFks] = useState<NewFk[]>([]);
  const [dropFks, setDropFks] = useState<string[]>([]);
  const [error, setError] = useState<string | null>(null);
  const [running, setRunning] = useState(false);

  const load = async () => {
    if (!tab.table) return;
    try {
      const st = await api.structure(tab.connectionId, tab.database, tab.schema, tab.table);
      setOrig(st);
      setCols(fromStructure(st));
      setComment(st.comment ?? '');
      setIndexes([]);
      setDropIdx([]);
      setFks([]);
      setDropFks([]);
      setError(null);
    } catch (e) {
      setError((e as Error).message);
    }
  };
  useEffect(() => {
    load();
  }, [tab.connectionId, tab.database, tab.schema, tab.table]);

  const qTable = useMemo(() => {
    const t = name.trim() || 'nouvelle_table';
    return kind === 'mysql' ? `${quoteIdent(kind, tab.database)}.${quoteIdent(kind, t)}` : `${quoteIdent(kind, tab.schema)}.${quoteIdent(kind, t)}`;
  }, [name, kind, tab.database, tab.schema]);

  const statements = useMemo(
    () => generateSql(kind, qTable, isNew, cols, orig, comment, indexes, dropIdx, fks, dropFks, tab.schema),
    [kind, qTable, isNew, cols, orig, comment, indexes, dropIdx, fks, dropFks, tab.schema],
  );

  const setCol = (key: string, p: Partial<Col>) => setCols((cs) => cs.map((c) => (c.key === key ? { ...c, ...p } : c)));
  const moveCol = (key: string, d: -1 | 1) =>
    setCols((cs) => {
      const i = cs.findIndex((c) => c.key === key);
      const j = i + d;
      if (j < 0 || j >= cs.length) return cs;
      const next = cs.slice();
      [next[i], next[j]] = [next[j], next[i]];
      return next;
    });

  const apply = async () => {
    if (!statements.length) return;
    if (isNew && !name.trim()) return toast('Donne un nom à la table.', 'error');
    if (conn?.production && !(await confirmDialog('Modifier la structure en production ?', statements.join(';\n\n') + ';', { danger: true, confirmLabel: 'Appliquer' }))) return;
    setRunning(true);
    const sid = 'designer-' + tab.id;
    const script = kind === 'postgres' ? ['BEGIN', ...statements, 'COMMIT'] : statements;
    try {
      const res = await api.execute(tab.connectionId, sid, tab.database, script.join(';\n') + ';');
      const err = res.find((r) => r.error);
      if (err) {
        if (kind === 'postgres') await api.execute(tab.connectionId, sid, tab.database, 'ROLLBACK').catch(() => {});
        setError(`${err.error}\n\nInstruction : ${err.statement}`);
        return;
      }
      setError(null);
      toast(isNew ? `Table ${name} créée` : 'Structure modifiée', 'success');
      invalidateCompletion(tab.connectionId);
      bumpTree(`${tab.connectionId}|${tab.database}|${tab.schema}`);
      if (isNew) updateTab(tab.id, { table: name.trim() });
      else await load();
    } catch (e) {
      setError((e as Error).message);
    } finally {
      api.closeSession(tab.connectionId, sid).catch(() => {});
      setRunning(false);
    }
  };

  const types = kind === 'postgres' ? PG_TYPES : MY_TYPES;
  const listId = `types-${tab.id}`;

  return (
    <div className={`pane ${active ? '' : 'hidden'}`}>
      <div className="toolbar">
        <button className="btn primary" disabled={!statements.length || running} onClick={apply}>
          <Play /> {isNew ? 'Créer la table' : 'Appliquer les modifications'}
        </button>
        {!isNew && (
          <button className="btn" onClick={load} title="Recharger depuis la base">
            <RotateCcw /> Recharger
          </button>
        )}
        <span className="sep" />
        <span className="hint">
          {connectionById(tab.connectionId)?.name} · {tab.database}
          {kind === 'postgres' ? ` · ${tab.schema}` : ''}
        </span>
      </div>
      {error && <div className="banner err">{error}</div>}
      <div className="page">
        <div className="form-grid" style={{ maxWidth: 820 }}>
          <label className="field">
            <span>Nom de la table</span>
            <input className="input mono" value={name} onChange={(e) => setName(e.target.value)} disabled={!isNew} autoFocus={isNew} placeholder="ex. factures" />
          </label>
          <label className="field">
            <span>Commentaire</span>
            <input className="input" value={comment} onChange={(e) => setComment(e.target.value)} />
          </label>
        </div>

        <h2 style={{ marginTop: 20 }}>Colonnes</h2>
        <datalist id={listId}>
          {types.map((t) => (
            <option key={t} value={t} />
          ))}
        </datalist>
        <table className="plain designer">
          <thead>
            <tr>
              <th style={{ width: 52 }} />
              <th>Nom</th>
              <th>Type</th>
              <th title="Accepte NULL">NULL</th>
              <th>Défaut (expression SQL)</th>
              <th title="Clé primaire">PK</th>
              <th title="Auto-incrément / identity">Auto</th>
              <th>Commentaire</th>
              <th style={{ width: 36 }} />
            </tr>
          </thead>
          <tbody>
            {cols.map((c) => (
              <tr key={c.key} className={`${c.removed ? 'removed' : ''} ${!c.orig ? 'isnew' : ''}`}>
                <td>
                  <button className="btn icon" style={{ width: 22, height: 22 }} onClick={() => moveCol(c.key, -1)} disabled={!!c.orig && kind === 'postgres'} title="Monter">
                    <ArrowUp />
                  </button>
                  <button className="btn icon" style={{ width: 22, height: 22 }} onClick={() => moveCol(c.key, 1)} disabled={!!c.orig && kind === 'postgres'} title="Descendre">
                    <ArrowDown />
                  </button>
                </td>
                <td>
                  <input className="input mono" value={c.name} onChange={(e) => setCol(c.key, { name: e.target.value })} disabled={c.removed} />
                </td>
                <td>
                  <input className="input mono" list={listId} value={c.type} onChange={(e) => setCol(c.key, { type: e.target.value })} disabled={c.removed} />
                </td>
                <td className="c">
                  <input type="checkbox" checked={c.nullable} onChange={(e) => setCol(c.key, { nullable: e.target.checked })} disabled={c.removed} />
                </td>
                <td>
                  <input className="input mono" value={c.def} placeholder={kind === 'postgres' ? "now(), 0, 'texte'" : "CURRENT_TIMESTAMP, 0, 'texte'"} onChange={(e) => setCol(c.key, { def: e.target.value })} disabled={c.removed} />
                </td>
                <td className="c">
                  <input type="checkbox" checked={c.pk} onChange={(e) => setCol(c.key, { pk: e.target.checked, nullable: e.target.checked ? false : c.nullable })} disabled={c.removed} />
                </td>
                <td className="c">
                  <input type="checkbox" checked={c.auto} onChange={(e) => setCol(c.key, { auto: e.target.checked })} disabled={c.removed} />
                </td>
                <td>
                  <input className="input" value={c.comment} onChange={(e) => setCol(c.key, { comment: e.target.value })} disabled={c.removed} />
                </td>
                <td>
                  {c.orig ? (
                    <button className="btn icon" onClick={() => setCol(c.key, { removed: !c.removed })} title={c.removed ? 'Restaurer' : 'Supprimer la colonne'}>
                      {c.removed ? <Undo2 /> : <Trash2 />}
                    </button>
                  ) : (
                    <button className="btn icon" onClick={() => setCols((cs) => cs.filter((x) => x.key !== c.key))} title="Retirer">
                      <Trash2 />
                    </button>
                  )}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
        <button className="btn outline" style={{ marginTop: 8 }} onClick={() => setCols((cs) => [...cs, blankCol(kind, false)])}>
          <Plus /> Ajouter une colonne
        </button>

        <h2>Index</h2>
        {orig && orig.indexes.filter((i) => !i.primary).length > 0 && (
          <table className="plain" style={{ marginBottom: 8 }}>
            <tbody>
              {orig.indexes
                .filter((i) => !i.primary)
                .map((i) => {
                  const dropped = dropIdx.includes(i.name);
                  return (
                    <tr key={i.name} style={dropped ? { opacity: 0.45, textDecoration: 'line-through' } : undefined}>
                      <td className="mono">{i.name}</td>
                      <td className="mono">{i.columns.join(', ')}</td>
                      <td>{i.unique ? <span className="pill uq">UNIQUE</span> : <span className="pill">INDEX</span>}</td>
                      <td style={{ width: 36 }}>
                        <button className="btn icon" onClick={() => setDropIdx((d) => (dropped ? d.filter((x) => x !== i.name) : [...d, i.name]))} title={dropped ? 'Conserver' : 'Supprimer l’index'}>
                          {dropped ? <Undo2 /> : <Trash2 />}
                        </button>
                      </td>
                    </tr>
                  );
                })}
            </tbody>
          </table>
        )}
        {indexes.map((i) => (
          <div className="form-row" key={i.key} style={{ marginBottom: 6 }}>
            <input className="input mono" style={{ width: 200 }} placeholder="nom (facultatif)" value={i.name} onChange={(e) => setIndexes((xs) => xs.map((x) => (x.key === i.key ? { ...x, name: e.target.value } : x)))} />
            <input className="input mono" style={{ flex: 1 }} placeholder="colonnes, séparées par des virgules" value={i.columns} onChange={(e) => setIndexes((xs) => xs.map((x) => (x.key === i.key ? { ...x, columns: e.target.value } : x)))} />
            <label className="check">
              <input type="checkbox" checked={i.unique} onChange={(e) => setIndexes((xs) => xs.map((x) => (x.key === i.key ? { ...x, unique: e.target.checked } : x)))} /> Unique
            </label>
            <button className="btn icon" onClick={() => setIndexes((xs) => xs.filter((x) => x.key !== i.key))}>
              <Trash2 />
            </button>
          </div>
        ))}
        <button className="btn outline" onClick={() => setIndexes((xs) => [...xs, { key: uid(), name: '', columns: '', unique: false }])}>
          <Plus /> Ajouter un index
        </button>

        <h2>Clés étrangères</h2>
        {orig && orig.foreignKeys.length > 0 && (
          <table className="plain" style={{ marginBottom: 8 }}>
            <tbody>
              {orig.foreignKeys.map((f) => {
                const dropped = dropFks.includes(f.name);
                return (
                  <tr key={f.name} style={dropped ? { opacity: 0.45, textDecoration: 'line-through' } : undefined}>
                    <td className="mono">{f.name}</td>
                    <td className="mono">
                      ({f.columns.join(', ')}) → {f.refTable}({f.refColumns.join(', ')})
                    </td>
                    <td className="hint">ON DELETE {f.onDelete}</td>
                    <td style={{ width: 36 }}>
                      <button className="btn icon" onClick={() => setDropFks((d) => (dropped ? d.filter((x) => x !== f.name) : [...d, f.name]))}>
                        {dropped ? <Undo2 /> : <Trash2 />}
                      </button>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        )}
        {fks.map((f) => {
          const set = (p: Partial<NewFk>) => setFks((xs) => xs.map((x) => (x.key === f.key ? { ...x, ...p } : x)));
          return (
            <div className="form-row" key={f.key} style={{ marginBottom: 6, flexWrap: 'wrap' }}>
              <input className="input mono" style={{ width: 160 }} placeholder="nom (facultatif)" value={f.name} onChange={(e) => set({ name: e.target.value })} />
              <input className="input mono" style={{ width: 150 }} placeholder="colonne(s)" value={f.columns} onChange={(e) => set({ columns: e.target.value })} />
              <span className="hint">→</span>
              <input className="input mono" style={{ width: 170 }} placeholder="table référencée" value={f.refTable} onChange={(e) => set({ refTable: e.target.value })} />
              <input className="input mono" style={{ width: 130 }} placeholder="colonne(s)" value={f.refColumns} onChange={(e) => set({ refColumns: e.target.value })} />
              <select className="input" value={f.onDelete} onChange={(e) => set({ onDelete: e.target.value })} title="ON DELETE">
                {FK_ACTIONS.map((a) => (
                  <option key={a}>{a}</option>
                ))}
              </select>
              <button className="btn icon" onClick={() => setFks((xs) => xs.filter((x) => x.key !== f.key))}>
                <Trash2 />
              </button>
            </div>
          );
        })}
        <button className="btn outline" onClick={() => setFks((xs) => [...xs, { key: uid(), name: '', columns: '', refTable: '', refColumns: 'id', onDelete: 'NO ACTION', onUpdate: 'NO ACTION' }])}>
          <Plus /> Ajouter une clé étrangère
        </button>

        <h2 style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
          <Code2 style={{ width: 16, height: 16 }} /> SQL généré
        </h2>
        <pre className="sql-preview">{statements.length ? statements.join(';\n\n') + ';' : '-- Aucune modification'}</pre>
        {kind === 'postgres' && statements.length > 0 && <p className="hint">Exécuté dans une transaction : en cas d’erreur, rien n’est appliqué.</p>}
        {kind === 'mysql' && statements.length > 0 && <p className="hint">MySQL valide chaque instruction DDL immédiatement (pas de retour arrière possible).</p>}
      </div>
    </div>
  );
}
